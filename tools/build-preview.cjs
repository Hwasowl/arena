// Bundles preview/ into one self-contained HTML: no module imports, no data: URLs (blocked in sandboxed frames).
const fs = require('fs'), path = require('path');
const [root, ...outs] = process.argv.slice(2);
require('./build-preview-assets.cjs');
const p = rel => fs.readFileSync(path.join(root, 'preview', rel), 'utf8').replace(/\r\n/g, '\n');
let three = p('vendor/three.module.js');
const m = three.match(/\nexport \{([^}]*)\};?\s*$/);
if (!m) throw new Error('three export block not found');
three = three.slice(0, m.index) + '\nreturn {' + m[1] + '};\n';
const importLine = "import * as T from './vendor/three.module.js';\n";
const app = p('app.js');
if (!app.startsWith(importLine)) throw new Error('unexpected app.js import');
const esc = s => s.split('</script').join('<\\/script');
const license = '<!--\n' + p('vendor/THREE-LICENSE.txt') + '\n-->\n';
const script = '<script>\nconst T=(function(){\n' + esc(three) + '\n})();\n(function(){\n' + esc(app.slice(importLine.length)) + '\n})();\n</script>';
let html = p('index.html');
const link = '<link rel="stylesheet" href="style.css">', tag = '<script type="module" src="app.js"></script>';
const assetTag = '<script src="skill-assets.js"></script>';
if (!html.includes(assetTag)) throw new Error('skill asset marker missing');
html = html.replace(assetTag, () => '<script>\n' + esc(p('skill-assets.js')) + '\n</script>');
const painTag = '<script src="pain.js"></script>';
if (!html.includes(painTag)) throw new Error('pain.js marker missing');
html = html.replace(painTag, () => '<script>\n' + esc(p('pain.js')) + '\n</script>');
const allMightTag = '<script src="allmight.js"></script>';
if (!html.includes(allMightTag)) throw new Error('allmight.js marker missing');
html = html.replace(allMightTag, () => '<script>\n' + esc(p('allmight.js')) + '\n</script>');
html=html.replace('<script src="kizaru.js"></script>',()=>'<script>\n'+esc(p('kizaru.js'))+'\n</script>');
const okkotsuTag='<script src="okkotsu.js"></script>';
if(!html.includes(okkotsuTag))throw new Error('okkotsu.js marker missing');
html=html.replace(okkotsuTag,()=>'<script>\n'+esc(p('okkotsu.js'))+'\n</script>');
const itachiTag = '<script src="itachi.js"></script>';
if (!html.includes(itachiTag)) throw new Error('itachi.js marker missing');
html = html.replace(itachiTag, () => '<script>\n' + esc(p('itachi.js')) + '\n</script>');
const yujiroTag = '<script src="yujiro.js"></script>';
if (!html.includes(yujiroTag)) throw new Error('yujiro.js marker missing');
html = html.replace(yujiroTag, () => '<script>\n' + esc(p('yujiro.js')) + '\n</script>');
if (!html.includes(link) || !html.includes(tag)) throw new Error('index.html markers missing');
html = html.replace(link, () => '<style>' + p('style.css') + '</style>').replace(tag, () => script).replace('<head>', () => '<head>\n' + license);
for (const out of outs) fs.writeFileSync(out, html.replace(/\r?\n/g, '\r\n'));
console.log('wrote', html.length, 'bytes');
