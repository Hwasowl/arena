// Embed the reviewed PNG/WAV files without data: URLs or runtime file requests.
const fs = require('fs'), path = require('path');
const root = path.resolve(process.argv[2] || '.');
const pack = path.join(root, 'assets/skill-pack-v1');
const manifest = JSON.parse(fs.readFileSync(path.join(pack, 'manifest.json'), 'utf8').replace(/^\uFEFF/, ''));
const encode = entries => Object.fromEntries(entries.map(e => [e.id, fs.readFileSync(path.join(pack, e.file)).toString('base64')]));
const icons = encode(manifest.icons), sounds = encode(manifest.sounds);
const source = `// Generated by tools/build-preview-assets.cjs from assets/skill-pack-v1/manifest.json.
(() => {
  const imageData = ${JSON.stringify(icons)};
  const soundData = ${JSON.stringify(sounds)};
  const icons = {}, urls = [];
  const bytes = text => Uint8Array.from(atob(text), c => c.charCodeAt(0));
  for (const id of Object.keys(imageData)) Object.defineProperty(icons, id, { enumerable: true, get() {
    const url = URL.createObjectURL(new Blob([bytes(imageData[id])], { type: 'image/png' }));
    urls.push(url); delete imageData[id];
    Object.defineProperty(icons, id, { value: url, enumerable: true }); return url;
  }, configurable: true });
  window.INFINITY_ASSETS = { icons, soundData, bytes };
  // Blob URLs remain valid across bfcache restoration; dispose only on a real unload.
  addEventListener('pagehide', e => { if (!e.persisted) urls.forEach(url => URL.revokeObjectURL(url)); });
})();
`;
fs.writeFileSync(path.join(root, 'preview/skill-assets.js'), source.replace(/\r?\n/g, '\r\n'));
console.log(`Embedded ${manifest.icons.length} icons and ${manifest.sounds.length} sounds (${source.length} bytes).`);
